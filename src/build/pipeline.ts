export interface BuildOptions { dryRun?: boolean; clean?: boolean }
export interface BuildPlan {
  root: string;
  report: AnalysisReport;
  configuration: AppConfiguration;
  manager: PackageManager;
  operations: { step: 'next' | 'sync' | 'gradle'; command: BuildCommand; cwd: string }[];
  clean: boolean;
}
const object = (v: unknown): Record<string, unknown> => {
  if (!v || typeof v !== 'object' || Array.isArray(v)) throw new Error('Expected an object in next2apk configuration.');
  return v as Record<string, unknown>;
};
function literal(node: ts.Expression): unknown {
  if (ts.isStringLiteral(node)) return node.text;
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(n => literal(n));
  if (ts.isObjectLiteralExpression(node)) {
    const result: Record<string, unknown> = Object.create(null) as Record<string, unknown>;
    for (const prop of node.properties) {
      if (!ts.isPropertyAssignment(prop) || (!ts.isIdentifier(prop.name) && !ts.isStringLiteral(prop.name)) || prop.name.text in result) throw new Error('Unsupported or duplicate Capacitor config property.');
      result[prop.name.text] = literal(prop.initializer);
    }
    return result;
  }
  throw new Error('Dynamic Capacitor config is unsupported during preflight; preserve the literal config generated by init.');
}
export function readCapacitorConfig(content: string): Record<string, unknown> {
  const source = ts.createSourceFile('capacitor.config.ts', content, ts.ScriptTarget.Latest, true);
  let value: unknown;
  let exported = false;
  for (const statement of source.statements) {
    if (ts.isImportDeclaration(statement) && statement.importClause?.isTypeOnly) continue;
    if (ts.isVariableStatement(statement) && statement.declarationList.declarations.length === 1 && statement.declarationList.flags & ts.NodeFlags.Const) {
      const declaration = statement.declarationList.declarations[0]!;
      if (!ts.isIdentifier(declaration.name) || declaration.name.text !== 'config' || !declaration.initializer || value !== undefined) throw new Error('Unsupported Capacitor config declaration.');
      value = literal(declaration.initializer);
    } else if (ts.isExportAssignment(statement) && statement.expression.getText(source) === 'config') exported = true;
    else throw new Error('Capacitor config must be the literal config generated by init; executable statements are refused.');
  }
  if (!exported) throw new Error('Capacitor config has no default export.');
  return object(value);
}
function configuration(value: unknown, strategy: string): AppConfiguration {
  const c = object(value);
  for (const key of ['appName', 'appId', 'webDir']) if (typeof c[key] !== 'string' || !c[key]) throw new Error(`Invalid state configuration.${key}. Run next2apk init first.`);
  if (strategy === 'REMOTE' && (!c.server || typeof object(c.server).url !== 'string')) throw new Error('REMOTE strategy requires a configured remote URL. Run next2apk init again with the appropriate configuration.');
  if (strategy !== 'REMOTE' && c.server !== undefined) throw new Error('Local strategy cannot use a remote server URL.');
  const result: AppConfiguration = { appName: c.appName as string, appId: c.appId as string, webDir: c.webDir as string, ...(strategy === 'REMOTE' ? { server: { url: object(c.server).url as string } } : {}) };
  generateConfig(result);
  if (strategy === 'REMOTE' ? result.webDir !== '.next2apk/remote-web' : !/^[A-Za-z0-9_-]+$/.test(result.webDir) || ['dist', 'src', 'app', 'pages', 'public', 'android', 'ios', 'static', 'node_modules'].includes(result.webDir)) throw new Error('Unsafe webDir or collision with dist/android. Use a dedicated export directory and consistent init configuration.');
  return result;
}
export async function planBuild(input = process.cwd(), options: BuildOptions = {}, platform: NodeJS.Platform = process.platform): Promise<BuildPlan> {
  const root = path.resolve(input);
  const report = await analyzeProject(root);
  const invalid = report.issues.filter(i => ['PACKAGE_MISSING', 'PACKAGE_INVALID', 'NEXT_MISSING', 'PACKAGE_MANAGER_CONFLICT', 'ROUTER_UNKNOWN', 'SOURCE_PARSE_REVIEW', 'SYMLINK_SKIPPED'].includes(i.code));
  if (invalid.length) throw new Error(invalid.map(i => `${i.code}: ${i.message}`).join('\n'));
  await assertSafePath(root, '.next2apk/state.json');
  if (!await exists(path.join(root, '.next2apk/state.json'))) throw new Error('next2apk is not initialized. Run next2apk init first.');
  let state: Record<string, unknown>;
  try { state = object(JSON.parse(await readFile(path.join(root, '.next2apk/state.json'), 'utf8'))); }
  catch { throw new Error('Invalid .next2apk/state.json. Restore a valid init state before building.'); }
  if (state.status !== 'completed' || typeof state.version !== 'string' || typeof state.date !== 'string' || !Number.isFinite(Date.parse(state.date)) || !['STATIC', 'HYBRID', 'REMOTE'].includes(String(state.strategy)) || typeof state.packageManager !== 'string' || !['createdFiles', 'modifiedFiles', 'removedFiles', 'backups'].every(key => Array.isArray(state[key]))) throw new Error('Invalid or incomplete init state. Complete next2apk init before building.');
  if (state.strategy !== report.strategy) throw new Error(`Strategy changed since init (${state.strategy} -> ${report.strategy}). Review and reconfigure the project before building.`);
  if (report.strategy !== 'REMOTE' && report.compatibility === 'FAIL') throw new Error(`${report.strategy} frontend is not exportable: ${report.issues.filter(i => i.severity === 'error').map(i => i.message).join(' ')}`);
  const config = configuration(state.configuration, report.strategy);
  const configs = await detectCapacitor(root);
  if (configs.length !== 1 || configs[0] !== 'capacitor.config.ts') throw new Error('Expected the capacitor.config.ts generated by init, without conflicting configurations. Run next2apk init first.');
  await assertSafePath(root, 'capacitor.config.ts');
  const actual = readCapacitorConfig(await readFile(path.join(root, 'capacitor.config.ts'), 'utf8'));
  if (JSON.stringify(configuration(actual, report.strategy)) !== JSON.stringify(config) || actual.android !== undefined) throw new Error('Capacitor configuration differs from init state or uses a custom Android path. Reconcile configuration before building.');
  const manager = selectPackageManager(report.packageManager, state.packageManager);
  const wrapper = platform === 'win32' ? 'gradlew.bat' : 'gradlew';
  for (const file of ['android/app/build.gradle', 'android/app/src/main/AndroidManifest.xml', `android/${wrapper}`, 'android/gradle/wrapper/gradle-wrapper.jar', 'android/gradle/wrapper/gradle-wrapper.properties', 'android/variables.gradle']) {
    await assertSafePath(root, file);
    if (!await exists(path.join(root, file)) || !(await lstat(path.join(root, file))).isFile()) throw new Error(`Missing Android project file: ${file}. Run next2apk init first; global Gradle is not required.`);
  }
  if (platform !== 'win32' && platform === process.platform) await access(path.join(root, 'android/gradlew'), constants.X_OK);
  for (const file of [config.webDir, 'dist/android', '.next2apk/init.lock']) await assertSafePath(root, file);
  if (await exists(path.join(root, '.next2apk/init.lock'))) throw new Error('Another init/build is running (.next2apk/init.lock exists).');
  if (report.strategy !== 'REMOTE') {
    if (report.configFiles.length !== 1) throw new Error('Expected a single static Next config created by init.');
    const file = report.configFiles[0]!;
    const content = await readFile(path.join(root, file), 'utf8');
    const prepared = prepareNextConfig(content, file);
    if (prepared.webDir !== config.webDir || !/\boutput\s*:\s*['"]export['"]/.test(content)) throw new Error('Next export configuration no longer matches init webDir/output.');
  }
  const operations: BuildPlan['operations'] = [];
  if (report.strategy !== 'REMOTE') operations.push({ step: 'next', command: binaryCommand(manager, 'next', ['build']), cwd: root });
  operations.push({ step: 'sync', command: binaryCommand(manager, 'cap', ['sync', 'android']), cwd: root });
  operations.push({ step: 'gradle', command: gradleCommand(platform, options.clean), cwd: path.join(root, 'android') });
  return { root, report, configuration: config, manager, operations, clean: options.clean ?? false };
}
